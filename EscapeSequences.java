public class EscapeSequences {
    public static void main(String[] args) {
// Newline
        System.out.println("Line 1\nLine 2\nLine 3");
// Tab
        System.out.println("Name:\tJohn");
        System.out.println("Age:\t25");
// Quotes
        System.out.println("He said, \"Hello!\"");
        System.out.println("It\'s a beautiful day");
// Backslash
        System.out.println("File path: C:\\Users\\Documents");
// Combining escape sequences
        System.out.println("Column1\tColumn2\tColumn3");
        System.out.println("Data1\tData2\tData3");
    }
}